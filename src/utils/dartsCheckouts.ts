export function getSuggestedCheckout(score: number): string | null {
  if (score < 2 || score > 170) return null;
  // Impossible finishes
  if ([169, 168, 166, 165, 163, 162, 159].includes(score)) return 'No 3-dart out';
  return COMMON_CHECKOUTS[score] || (score <= 40 && score % 2 === 0 ? `D${score / 2}` : null);
}
